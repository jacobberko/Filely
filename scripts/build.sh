#!/bin/bash
set -euo pipefail

project_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
configuration="${1:-debug}"
case "$configuration" in
    debug|release) ;;
    *) printf 'Usage: %s [debug|release]\n' "$0" >&2; exit 64 ;;
esac

if [[ -z "${DEVELOPER_DIR:-}" && -d /Applications/Xcode.app/Contents/Developer ]]; then
    export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
fi

cache_root="$project_root/.build-cache"
build_root="$project_root/build"
export CLANG_MODULE_CACHE_PATH="$cache_root/clang"
export SWIFTPM_MODULECACHE_OVERRIDE="$cache_root/swift"
mkdir -p "$CLANG_MODULE_CACHE_PATH" "$SWIFTPM_MODULECACHE_OVERRIDE" \
    "$cache_root/packages" "$cache_root/configuration" "$cache_root/security" "$build_root"

swift_options=(
    --build-system native
    --package-path "$project_root"
    --scratch-path "$project_root/.build"
    --cache-path "$cache_root/packages"
    --config-path "$cache_root/configuration"
    --security-path "$cache_root/security"
    --disable-sandbox
    --configuration "$configuration"
)

printf 'Building Filer (%s)…\n' "$configuration"
/usr/bin/xcrun swift build "${swift_options[@]}" --product Filer
binary_directory="$(/usr/bin/xcrun swift build "${swift_options[@]}" --show-bin-path)"
binary="$binary_directory/Filer"
if [[ ! -x "$binary" ]]; then
    printf 'The build succeeded but the Filer executable was not found at %s\n' "$binary" >&2
    exit 1
fi

iconset="$build_root/Filer.iconset"
# These paths contain only artifacts generated by this script, never user-selected documents.
rm -rf -- "$iconset"
# Keep standalone compiler modules outside the synced project tree.
icon_module_cache="${TMPDIR:-/tmp}/filer-icon-module-cache"
mkdir -p "$icon_module_cache"
CLANG_MODULE_CACHE_PATH="$icon_module_cache" /usr/bin/xcrun swift -module-cache-path "$icon_module_cache" \
    "$project_root/scripts/make-icon.swift" "$iconset" "$build_root/Filer.icns"
if /usr/bin/iconutil --convert icns "$iconset" --output "$build_root/Filer-iconutil.icns" 2>/dev/null; then
    mv -- "$build_root/Filer-iconutil.icns" "$build_root/Filer.icns"
else
    printf 'Using the native ICNS encoding verified by AppKit.\n'
fi

# Package outside the synced workspace so File Provider cannot add Finder
# metadata between cleanup and codesigning.
package_root="$(mktemp -d "${TMPDIR:-/tmp}/filer-package.XXXXXX")"
trap 'rm -rf -- "$package_root"' EXIT
staging="$package_root/Filer.app"
application="$build_root/Filer.app"
rm -rf -- "$build_root/Filer-staging.app"
mkdir -p "$staging/Contents/MacOS" "$staging/Contents/Resources"
/usr/bin/install -m 755 "$binary" "$staging/Contents/MacOS/Filer"
/usr/bin/install -m 644 "$project_root/Resources/Info.plist" "$staging/Contents/Info.plist"

shopt -s dotglob nullglob
for resource in "$project_root/Resources/"*; do
    name="$(basename -- "$resource")"
    [[ "$name" == Info.plist || "$name" == .DS_Store ]] && continue
    /usr/bin/ditto "$resource" "$staging/Contents/Resources/$name"
done
/usr/bin/install -m 644 "$build_root/Filer.icns" "$staging/Contents/Resources/Filer.icns"

# Finder/iCloud can decorate generated bundles in a synced workspace. Remove only
# the two metadata attributes codesign rejects, and only from our new artifact.
/usr/bin/xattr -dr com.apple.FinderInfo "$staging" 2>/dev/null || true
/usr/bin/xattr -dr com.apple.ResourceFork "$staging" 2>/dev/null || true
# This is local ad-hoc signing, not a notarized distribution build. A changed
# executable can require refreshing its existing Accessibility permission.
/usr/bin/codesign --force --sign - --timestamp=none \
    --identifier com.jacobberko.filer.prototype "$staging"
/usr/bin/codesign --verify --strict "$staging"

# Replace the previous generated bundle only after compilation, icon generation, and signing succeed.
rm -rf -- "$application"
mv -- "$staging" "$application"
printf 'Built %s\n' "$application"
printf 'Open it with: open "%s"\n' "$application"
